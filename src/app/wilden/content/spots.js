// התיבה שהדמות באמת תופסת על התפאורה, באחוזים. התפאורה היא 3:4, ולכן
// אחוז גובה שווה ל-4/3 אחוזי רוחב.
export function figureBox(id, spot) {
  const f = FIGURE[id]
  if (!f || !spot) return null
  const h = spot.h
  const cw = h * (4 / 3) * f.ratio                 // רוחב הקנבס באחוזי רוחב
  const figH = h * (f.bot - f.top)                 // גובה הדמות עצמה
  return { left: spot.x - (cw * f.w) / 2, right: spot.x + (cw * f.w) / 2, bottom: spot.y, top: spot.y - figH }
}

// המרווח הקטן ביותר בין שתי תיבות. שלילי = נוגעות.
export function gapBetween(a, b) {
  if (!a || !b) return Infinity
  const dx = Math.max(a.left, b.left) - Math.min(a.right, b.right)
  const dy = Math.max(a.top, b.top) - Math.min(a.bottom, b.bottom)
  return Math.max(dx, dy)
}
