// ─── הגיאומטריה של האלומה ───
// טהור, בלי JSX — כדי שגם הבדיקה תוכל לייבא אותו, ולא תשכפל את המספרים
// אצלה ותיפרד מהם בשקט. Lantern.js מצייר מהם, והבמה בודקת מהם.

// ── איפה האלומה, ומה בתוכה ──
// הכול באחוזי *רוחב*, כמו ה-SVG שמצייר. BEAM_Y הוא מרכז הכתם כחלק
// מגובה המסך — והמבחן נמדד ממנו, ולא ממרכז המסך.
export const BEAM_Y = 0.62       // מרכז הכתם, כחלק מגובה המסך

// ── ולמה עיגול, וגדול ──
// "האור קטן מדי על המסך. בא לי שכשאלחץ יש מהחושך עיגול מואר גדול."
// הכתם היה אליפסה שטוחה — 44 רוחב על 22 גובה — כי אור שנופל על רצפה
// הוא אליפסה. זה היה נכון פיזיקלית ושגוי על מסך: בגובה של 22 הוא יצא
// פס דק, והחור בחושך היה קטן אף יותר ממנו. עכשיו זה עיגול אחד גדול:
// 42 אחוזי רוחב לרדיוס, כלומר כ-84% מרוחב המסך לקוטר. והוא גם עלה,
// מ-74% מגובה המסך ל-62% — "העיגול אור לא גדול ונמוך מדי, זה לא נוח":
// הוא היה מודבק לקצה התחתון, וכל החצי העליון של המסך נשאר שחור וריק.
export const BEAM_R = 42
// שמות ישנים, לאותו מספר — כדי ששום מקום לא יישבר בשקט.
export const BEAM_RX = BEAM_R
export const BEAM_RY = BEAM_R

// aspect = גובה/רוחב של המסך. בלעדיו אי אפשר להשוות מרחק אנכי (שנמדד
// באחוזי גובה) לרדיוס שמצויר באחוזי רוחב — וזה בדיוק מה שהיה שבור.
export const beamHit = (dx, dy, fov, aspect = 2.2) => {
  if (dx == null || dy == null) return false
  const bx = (dx / (fov / 2)) * 50                      // אחוזי רוחב מהמרכז
  const topPct = 52 - dy * 1.5                          // איפה היצור, באחוזי גובה
  const by = (topPct - BEAM_Y * 100) * aspect           // ההפרש, מומר לאחוזי רוחב
  return bx * bx + by * by <= BEAM_R * BEAM_R
}
